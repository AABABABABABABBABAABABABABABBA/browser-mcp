import { z } from "zod";
import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { ToolDef, ok, err } from "../types.js";

const GRANT_VALUES = [
  "none", "unsafeWindow",
  "GM_setValue", "GM_getValue", "GM_deleteValue", "GM_listValues",
  "GM_setClipboard", "GM_notification",
  "GM_openInTab", "GM_registerMenuCommand", "GM_unregisterMenuCommand",
  "GM_addStyle", "GM_getResourceText", "GM_getResourceURL",
  "GM_xmlhttpRequest", "GM_download",
  "GM.setValue", "GM.getValue", "GM.deleteValue", "GM.listValues",
  "GM.setClipboard", "GM.notification", "GM.openInTab",
  "GM.xmlHttpRequest",
] as const;

function buildHeader(opts: any): string {
  const lines: string[] = ["// ==UserScript=="];
  const row = (k: string, v: string) => lines.push(`// @${k.padEnd(14)} ${v}`);
  row("name", opts.name);
  if (opts.namespace) row("namespace", opts.namespace);
  if (opts.version) row("version", opts.version);
  if (opts.description) row("description", opts.description);
  if (opts.author) row("author", opts.author);
  if (opts.homepage) row("homepage", opts.homepage);
  if (opts.icon) row("icon", opts.icon);
  for (const m of opts.matches ?? []) row("match", m);
  for (const i of opts.includes ?? []) row("include", i);
  for (const e of opts.excludes ?? []) row("exclude", e);
  for (const g of opts.grants ?? ["none"]) row("grant", g);
  for (const r of opts.requires ?? []) row("require", r);
  for (const c of opts.connects ?? []) row("connect", c);
  if (opts.runAt) row("run-at", opts.runAt);
  if (opts.noframes) row("noframes", "");
  lines.push("// ==/UserScript==");
  return lines.join("\n");
}

export const userscriptTools: ToolDef[] = [
  {
    name: "userscript_build",
    description: "Build a Tampermonkey / Violentmonkey userscript (.user.js) from a header spec and a body of JavaScript. Returns the full file text; optionally also saves it to disk.",
    schema: z.object({
      name: z.string(),
      body: z.string().describe("the userscript's JS. Wrapped in an IIFE automatically unless wrapIIFE=false."),
      namespace: z.string().optional(),
      version: z.string().optional(),
      description: z.string().optional(),
      author: z.string().optional(),
      homepage: z.string().optional(),
      icon: z.string().optional(),
      matches: z.array(z.string()).optional().describe('e.g. ["https://www.roblox.com/*"]'),
      includes: z.array(z.string()).optional(),
      excludes: z.array(z.string()).optional(),
      grants: z.array(z.enum(GRANT_VALUES)).optional(),
      requires: z.array(z.string()).optional().describe("URLs to load as dependencies"),
      connects: z.array(z.string()).optional().describe("hosts GM_xmlhttpRequest may contact"),
      runAt: z.enum(["document-start", "document-body", "document-end", "document-idle", "context-menu"]).optional(),
      noframes: z.boolean().optional(),
      wrapIIFE: z.boolean().optional().describe("default true — wraps body in (() => { ... })()"),
      strict: z.boolean().optional().describe("default true — prepends 'use strict'"),
      savePath: z.string().optional().describe("if given, writes the file to this path and returns both"),
    }),
    handler: async (a) => {
      if (!a.matches?.length && !a.includes?.length) return err("supply at least one `matches` or `includes` pattern");
      const header = buildHeader(a);
      const strict = a.strict !== false ? '  "use strict";\n' : "";
      const wrap = a.wrapIIFE !== false;
      const body = wrap ? `(() => {\n${strict}${a.body}\n})();` : a.body;
      const script = `${header}\n\n${body}\n`;
      if (a.savePath) {
        const p = resolve(a.savePath);
        await writeFile(p, script, "utf8");
        return ok({ path: p, bytes: script.length, script });
      }
      return ok({ script });
    },
  },
  {
    name: "userscript_from_console_eval",
    description: "Convenience wrapper: given a snippet that already works when pasted into DevTools console on target URLs, wrap it into a .user.js with sensible defaults.",
    schema: z.object({
      name: z.string(),
      targetUrls: z.array(z.string()).min(1).describe("URL patterns, e.g. ['https://www.roblox.com/*']"),
      consoleSnippet: z.string(),
      runAt: z.enum(["document-start", "document-end", "document-idle"]).optional(),
      grants: z.array(z.enum(GRANT_VALUES)).optional(),
      savePath: z.string().optional(),
    }),
    handler: async (a) => {
      const header = buildHeader({
        name: a.name,
        namespace: "browser-mcp",
        version: "0.1.0",
        description: `Auto-generated by browser-mcp from a console snippet`,
        matches: a.targetUrls,
        grants: a.grants ?? ["none"],
        runAt: a.runAt ?? "document-end",
      });
      const script = `${header}\n\n(() => {\n  "use strict";\n${a.consoleSnippet}\n})();\n`;
      if (a.savePath) {
        const p = resolve(a.savePath);
        await writeFile(p, script, "utf8");
        return ok({ path: p, bytes: script.length, script });
      }
      return ok({ script });
    },
  },
];
