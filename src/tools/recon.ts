// MurmurHash3 32-bit — matches Shodan's favicon hash
function mmh3_32(buf: Buffer, seed = 0): number {
  const c1 = 0xcc9e2d51 | 0, c2 = 0x1b873593 | 0, n = buf.length;
  let h = seed | 0;
  const nblocks = Math.floor(n / 4);
  for (let i = 0; i < nblocks; i++) {
    let k = buf.readInt32LE(i * 4);
    k = Math.imul(k, c1); k = (k << 15) | (k >>> 17); k = Math.imul(k, c2);
    h ^= k; h = (h << 13) | (h >>> 19); h = Math.imul(h, 5) + 0xe6546b64 | 0;
  }
  let k = 0;
  const tail = nblocks * 4;
  switch (n & 3) {
    case 3: k ^= buf[tail + 2] << 16;
    case 2: k ^= buf[tail + 1] << 8;
    case 1: k ^= buf[tail]; k = Math.imul(k, c1); k = (k << 15) | (k >>> 17); k = Math.imul(k, c2); h ^= k;
  }
  h ^= n; h ^= h >>> 16; h = Math.imul(h, 0x85ebca6b); h ^= h >>> 13;
  h = Math.imul(h, 0xc2b2ae35); h ^= h >>> 16;
  return h | 0;
}

